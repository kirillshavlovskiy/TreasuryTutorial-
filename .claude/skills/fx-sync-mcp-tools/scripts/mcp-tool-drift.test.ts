describe('scanTreasuryRepo — against a fake checkout on disk', () => {
  let tmpDir: string;

  afterEach(() => {
    if (tmpDir) fs.rmSync(tmpDir, { recursive: true, force: true });
  });

  function writeFakeCheckout(files: Record<string, string>): string {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fx-sync-mcp-tools-test-'));
    for (const [relativePath, content] of Object.entries(files)) {
      const fullPath = path.join(dir, relativePath);
      fs.mkdirSync(path.dirname(fullPath), { recursive: true });
      fs.writeFileSync(fullPath, content, 'utf8');
    }
    return dir;
  }

  it('returns null when registered_tools.ts is absent (not a treasury checkout)', () => {
    tmpDir = writeFakeCheckout({ 'package.json': '{}' });
    expect(scanTreasuryRepo(tmpDir)).toBeNull();
  });

  it('parses a minimal fake checkout end to end', () => {
    tmpDir = writeFakeCheckout({
      'app/src/mcp/lib/registered_tools.ts': [
        "import * as fakeReadOnlyTool from '../tools/fake_domain/fake_read_only_tool';",
        "import * as fakeMutatingTool from '../tools/fake_domain/fake_mutating_tool';",
        "import * as fakeHelper from '../tools/fake_domain/fake_helper';",
        "",
        "export const registeredFinanceToolModules: ToolModule[] = [",
        "    fakeReadOnlyTool,",
        "    fakeMutatingTool,",
        "    fakeHelper,",
        "] as unknown as ToolModule[];",
      ].join('\n'),
      'app/src/mcp/lib/trimming_hints.ts': [
        "export const RESPONSE_TRIMMING_HINT = {",
        "    fakeHint: 'Trim: fields [\"a\"].',",
        "} as const;",
      ].join('\n'),
      'app/src/mcp/tools/fake_domain/fake_read_only_tool.ts': [
        "export const metadata: FinanceToolMetadata = {",
        "    name: 'fake_read_only_tool',",
        "    description: 'Reads a fake thing. ' + RESPONSE_TRIMMING_HINT.fakeHint,",
        "    requiredPermissions: {fake_resource: 'READ'},",
        "    annotations: {readOnlyHint: true},",
        "};",
      ].join('\n'),
      'app/src/mcp/tools/fake_domain/fake_mutating_tool.ts': [
        "export const metadata: FinanceToolMetadata = {",
        "    name: 'fake_mutating_tool',",
        "    description: 'Mutates a fake thing.',",
        "    requiredPermissions: {fake_resource: 'EDIT'},",
        "};",
      ].join('\n'),
      // Helper module: exports no `metadata`, matching lazy_deps.ts / shared_context.ts in the
      // real repo. Must not appear in scan results and must not crash the scan.
      'app/src/mcp/tools/fake_domain/fake_helper.ts': "export function fakeHelperFn() {}",
    });

    const tools = scanTreasuryRepo(tmpDir);
    expect(tools).not.toBeNull();
    expect(tools!.map((t) => t.name).sort()).toEqual(['fake_mutating_tool', 'fake_read_only_tool']);

    const readOnlyTool = tools!.find((t) => t.name === 'fake_read_only_tool')!;
    expect(readOnlyTool.description).toBe('Reads a fake thing. Trim: fields ["a"].');
    expect(readOnlyTool.readOnly).toBe(true);

    const mutatingTool = tools!.find((t) => t.name === 'fake_mutating_tool')!;
    expect(mutatingTool.readOnly).toBe(false);
  });

  it('treats a resolved but unreadable import path as excluded, not a crash', () => {
    tmpDir = writeFakeCheckout({
      'app/src/mcp/lib/registered_tools.ts': [
        "import * as fakeGhostTool from '../tools/fake_domain/fake_ghost_tool';",
        "",
        "export const registeredFinanceToolModules: ToolModule[] = [",
        "    fakeGhostTool,",
        "] as unknown as ToolModule[];",
      ].join('\n'),
      // fake_ghost_tool.ts deliberately not written to disk.
    });
    expect(scanTreasuryRepo(tmpDir)).toEqual([]);
  });
});

describe('analyseDrift', () => {
  function catalogue(names: string[], overrides: { description?: Map<string, string>; readOnly?: Map<string, boolean> } = {}) {
    return {
      names,
      descriptionByName: overrides.description ?? new Map(names.map((n) => [n, `${n} description`])),
      readOnlyByName: overrides.readOnly ?? new Map(names.map((n) => [n, true])),
    };
  }

  it('reports no drift when catalogue and repo match exactly', () => {
    const repoTools = [{ name: 'fake_tool', description: 'fake_tool description', readOnly: true }];
    const result = analyseDrift(catalogue(['fake_tool']), repoTools);
    expect(result.hasDrift).toBe(false);
  });

  it('reports a tool in the repo but not in the catalogue', () => {
    const repoTools = [
      { name: 'fake_tool', description: 'fake_tool description', readOnly: true },
      { name: 'fake_new_tool', description: 'brand new', readOnly: true },
    ];
    const result = analyseDrift(catalogue(['fake_tool']), repoTools);
    expect(result.inRepoNotInCatalogue).toEqual(['fake_new_tool']);
    expect(result.hasDrift).toBe(true);
  });

  it('reports a tool in the catalogue but not in the repo (stale checkout or removed tool)', () => {
    const repoTools = [{ name: 'fake_tool', description: 'fake_tool description', readOnly: true }];
    const result = analyseDrift(catalogue(['fake_tool', 'fake_removed_tool']), repoTools);
    expect(result.inCatalogueNotInRepo).toEqual(['fake_removed_tool']);
    expect(result.hasDrift).toBe(true);
  });

  it('reports a changed description for a tool present in both', () => {
    const repoTools = [{ name: 'fake_tool', description: 'a NEW description', readOnly: true }];
    const result = analyseDrift(catalogue(['fake_tool']), repoTools);
    expect(result.descriptionChanged).toEqual(['fake_tool']);
    expect(result.hasDrift).toBe(true);
  });

  // The catalogue's markdown table cells are single-line (a raw newline breaks a table row), so
  // a multi-paragraph backtick-literal description (several real tools use one, e.g.
  // download_vendor_bill_pdf) is flattened when the table is generated. Without normalizing both
  // sides the same way, every one of those tools would report as "changed" on every run.
  it('does not report drift for a description that differs only in whitespace/newlines', () => {
    const repoTools = [
      { name: 'fake_tool', description: 'Fake summary.\n\nSecond paragraph.  Third.', readOnly: true },
    ];
    const result = analyseDrift(
      catalogue(['fake_tool'], {
        description: new Map([['fake_tool', 'Fake summary. Second paragraph. Third.']]),
      }),
      repoTools
    );
    expect(result.descriptionChanged).toEqual([]);
    expect(result.hasDrift).toBe(false);
  });

  it('reports a tool that flipped from read-only to mutating', () => {
    const repoTools = [{ name: 'fake_tool', description: 'fake_tool description', readOnly: false }];
    const result = analyseDrift(catalogue(['fake_tool']), repoTools);
    expect(result.readOnlyFlagChanged).toEqual(['fake_tool']);
    expect(result.hasDrift).toBe(true);
  });
});

describe('formatUnexpectedError', () => {
  // Verified against a real throwing stand-in script by an independent Opus 5 review: without
  // this wrapper, an unexpected exception printed a full Node stack trace to stderr and exited 1
  // at session start. A SessionStart hook must fail open, never crash-looking, the same principle
  // .claude/hooks/protected-paths.mjs's own header states for its PreToolUse hook.
  it('exits 0 with a friendly message in staleness mode, never a stack trace', () => {
    const result = formatUnexpectedError(new Error('fake failure'), true);
    expect(result.exitCode).toBe(0);
    expect(result.message).not.toContain('at ');
    expect(result.message).toContain('run /fx-sync-mcp-tools');
  });

  it('exits 1 with a SCAN FAILED message in drift mode', () => {
    const result = formatUnexpectedError(new Error('fake failure'), false);
    expect(result.exitCode).toBe(1);
    expect(result.message).toContain('RESULT: SCAN FAILED');
    expect(result.message).toContain('fake failure');
  });

  it('handles a non-Error thrown value without crashing itself', () => {
    const result = formatUnexpectedError('a thrown string, not an Error', true);
    expect(result.exitCode).toBe(0);
    expect(result.message).toContain('run /fx-sync-mcp-tools');
  });
});

describe('parseCatalogueTools', () => {
  it('reads a read-only table row into descriptionByName and readOnlyByName', () => {
    const catalogue = [
      '## Read-only catalogue by domain',
      '',
      '### Fake Domain',
      '',
      '| Tool | Permission | Description |',
      '|---|---|---|',
      "| `fake_read_only_tool` | `fake_resource: 'READ'` | Reads a fake thing. |",
      '',
      '## Mutating tools — never call',
      '',
    ].join('\n');
    const { descriptionByName, readOnlyByName } = parseCatalogueTools(catalogue);
    expect(descriptionByName.get('fake_read_only_tool')).toBe('Reads a fake thing.');
    expect(readOnlyByName.get('fake_read_only_tool')).toBe(true);
  });

  it('reads a mutating table name into readOnlyByName only, never descriptionByName', () => {
    const catalogue = [
      '## Read-only catalogue by domain',
      '',
      '## Mutating tools — never call',
      '',
      '### Fake Domain',
      '',
      '| Tool | Permission |',
      '|---|---|',
      "| `fake_mutating_tool` | `fake_resource: 'CREATE'` |",
      '',
    ].join('\n');
    const { descriptionByName, readOnlyByName } = parseCatalogueTools(catalogue);
    expect(readOnlyByName.get('fake_mutating_tool')).toBe(false);
    expect(descriptionByName.has('fake_mutating_tool')).toBe(false);
  });

  // Found by an independent Opus 5 review, against a real generated catalogue: a whole-file
  // multiline regex let `[^|]*` and a lazy `(.+?)` cross the newline out of a short (2-column)
  // mutating row and into the FOLLOWING row, fabricating a bogus "description" for the first
  // row's tool name out of the second row's content — reported as real drift on
  // `tms_create_financial_account` where none existed. This reproduces that exact shape: a
  // 2-column mutating row immediately followed by another row.
  it('does not fabricate a description for a mutating tool from the row that follows it', () => {
    const catalogue = [
      '## Mutating tools — never call',
      '',
      '### Fake Domain',
      '',
      '| Tool | Permission |',
      '|---|---|',
      "| `fake_mutating_one` | `fake_resource: 'CREATE'` |",
      "| `fake_mutating_two` | `fake_resource: 'EDIT'` |",
      '',
    ].join('\n');
    const { descriptionByName, readOnlyByName } = parseCatalogueTools(catalogue);
    expect(descriptionByName.has('fake_mutating_one')).toBe(false);
    expect(descriptionByName.has('fake_mutating_two')).toBe(false);
    expect(readOnlyByName.get('fake_mutating_one')).toBe(false);
    expect(readOnlyByName.get('fake_mutating_two')).toBe(false);
  });

  it('does not fabricate a description crossing from a mutating row into a following read-only table', () => {
    const catalogue = [
      '## Mutating tools — never call',
      '',
      '### Fake Domain',
      '',
      '| Tool | Permission |',
      '|---|---|',
      "| `fake_mutating_tool` | `fake_resource: 'CREATE'` |",
      '',
      '## Read-only catalogue by domain',
      '',
      '### Fake Domain',
      '',
      '| Tool | Permission | Description |',
      '|---|---|---|',
      "| `fake_read_only_tool` | `fake_resource: 'READ'` | Reads a fake thing. |",
    ].join('\n');
    const { descriptionByName, readOnlyByName } = parseCatalogueTools(catalogue);
    expect(descriptionByName.has('fake_mutating_tool')).toBe(false);
    expect(readOnlyByName.get('fake_mutating_tool')).toBe(false);
    expect(descriptionByName.get('fake_read_only_tool')).toBe('Reads a fake thing.');
  });

  it('unescapes a literal pipe in a description read back from a table row', () => {
    const catalogue = [
      '## Read-only catalogue by domain',
      '',
      '| Tool | Permission | Description |',
      '|---|---|---|',
      "| `fake_tool` | `fake_resource: 'READ'` | balanceBasis (\"a\" \\| \"b\"). |",
    ].join('\n');
    const { descriptionByName } = parseCatalogueTools(catalogue);
    expect(descriptionByName.get('fake_tool')).toBe('balanceBasis ("a" | "b").');
  });

  // Found by an independent Opus 5 review: "Deep reference" has its own 4-column
  // `| Param | Type | Required | Description |` tables, and a PARAMETER row matches the same
  // 3-group tool-row pattern just as well as a real tool row does — it fabricated a bogus
  // descriptionByName entry keyed by a parameter name (`currency`, `limit`, `date`, …) instead of
  // a tool name. Harmless only by coincidence (no parameter happened to share a name with a real
  // tool) until now.
  it('does not treat a Deep reference parameter row as a tool row', () => {
    const catalogue = [
      '## Read-only catalogue by domain',
      '',
      '| Tool | Permission | Description |',
      '|---|---|---|',
      "| `fake_read_only_tool` | `fake_resource: 'READ'` | Reads a fake thing. |",
      '',
      '## Mutating tools — never call',
      '',
      '## Deep reference',
      '',
      '#### `fake_read_only_tool`',
      '',
      'Reads a fake thing.',
      '',
      '| Param | Type | Required | Description |',
      '|---|---|---|---|',
      '| `currency` | string | no | Currency code. |',
    ].join('\n');
    const { descriptionByName } = parseCatalogueTools(catalogue);
    expect(descriptionByName.get('fake_read_only_tool')).toBe('Reads a fake thing.');
    expect(descriptionByName.has('currency')).toBe(false);
  });

  // Found by the same review: `$` without the `m` flag already matches end-of-string OR just
  // before a single trailing newline at the very end of the string. The original lookahead
  // `(?=\n## |\n$)` required an EXTRA explicit `\n` beyond that, so a catalogue whose mutating
  // section is the very last thing in the file — no trailing blank line, no following heading —
  // matched nothing at all, silently losing every mutating classification. That is the more
  // dangerous failure direction: it reports IN SYNC while having verified nothing.
  it('finds mutating tool names when the section is the last thing in the file, with no trailing heading', () => {
    const catalogue = [
      '## Mutating tools — never call',
      '',
      "| `fake_mutating_tool` | `fake_resource: 'CREATE'` |",
    ].join('\n');
    const { readOnlyByName } = parseCatalogueTools(catalogue);
    expect(readOnlyByName.get('fake_mutating_tool')).toBe(false);
  });
});
