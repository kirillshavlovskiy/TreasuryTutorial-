describe('parseTrimmingHints', () => {
  it('extracts a simple single-quoted entry', () => {
    const source = "export const RESPONSE_TRIMMING_HINT = {\n  fakeHint: 'Trim: fields [\"a\"].',\n} as const;";
    expect(parseTrimmingHints(source)).toEqual({ fakeHint: 'Trim: fields ["a"].' });
  });

  it('joins a concatenated multi-line entry', () => {
    const source = [
      'export const RESPONSE_TRIMMING_HINT = {',
      "    fakeHint:",
      "        'Trim: fields [\"a\",\"b\"] ' +",
      "        'or omit [\"c\"].',",
      '} as const;',
    ].join('\n');
    expect(parseTrimmingHints(source).fakeHint).toBe('Trim: fields ["a","b"] or omit ["c"].');
  });

  it('extracts multiple entries', () => {
    const source = [
      'export const RESPONSE_TRIMMING_HINT = {',
      "    fakeOne: 'First hint.',",
      "    fakeTwo: 'Second hint.',",
      '} as const;',
    ].join('\n');
    expect(parseTrimmingHints(source)).toEqual({ fakeOne: 'First hint.', fakeTwo: 'Second hint.' });
  });

  it('returns empty when the object is absent', () => {
    expect(parseTrimmingHints('export const SOMETHING_ELSE = {};')).toEqual({});
  });

  // The real trimming_hints.ts only uses single quotes today, but the value-matching alternation
  // previously had no backtick branch — a hint written as a template literal wouldn't even be
  // recognized as a value by the outer entry pattern, so the whole entry silently failed to
  // match rather than partially matching. Found by an independent Opus 5 review.
  it('extracts a backtick template-literal entry', () => {
    const source = "export const RESPONSE_TRIMMING_HINT = {\n  fakeHint: `Trim: fields [\"a\"].`,\n} as const;";
    expect(parseTrimmingHints(source)).toEqual({ fakeHint: 'Trim: fields ["a"].' });
  });
});

describe('resolveDescription', () => {
  it('joins plain concatenated string literals', () => {
    const raw = "'Fake tool description. ' + 'Second sentence.'";
    expect(resolveDescription(raw, {})).toBe('Fake tool description. Second sentence.');
  });

  // download_vendor_bill_pdf and 69 other real tools (70 of 219, ≈32% — measured directly via
  // `grep -rlP "description:\s*\n?\s*\x60" app/src/mcp/tools/` against the treasury checkout, not
  // guessed) write their description as one backtick template literal instead of concatenated
  // quotes. Missing this left all 70 with an empty description on the first generation pass.
  it('reads a backtick template literal description', () => {
    const raw = '`Fake multi-line description.\n\nSecond paragraph.`';
    expect(resolveDescription(raw, {})).toBe('Fake multi-line description.\n\nSecond paragraph.');
  });

  it('appends a resolved RESPONSE_TRIMMING_HINT reference', () => {
    const raw = "'Fake tool description. ' + RESPONSE_TRIMMING_HINT.fakeHint";
    expect(resolveDescription(raw, { fakeHint: 'Trim: fields ["a"].' })).toBe(
      'Fake tool description. Trim: fields ["a"].'
    );
  });

  it('leaves an unknown hint key silently unresolved rather than throwing', () => {
    const raw = "'Fake tool description. ' + RESPONSE_TRIMMING_HINT.unknownHint";
    expect(resolveDescription(raw, {})).toBe('Fake tool description.');
  });

  // At least 8 real tools (ns_get_vendor_bill.ts and others) write the hint as a template-literal
  // INTERPOLATION inside the backtick description, not as a `+`-concatenated reference. An
  // earlier version of this function only handled the `+` form: it left the literal
  // "${RESPONSE_TRIMMING_HINT.x}" text in place (extracted verbatim by the backtick-literal
  // regex) AND additionally appended a duplicate copy of the resolved hint onto the very end of
  // the whole description, in the wrong position. Found by an independent Opus 5 review.
  it('resolves a ${RESPONSE_TRIMMING_HINT.key} interpolation inside a backtick literal, in place', () => {
    const raw = '`Fake summary.\n\n${RESPONSE_TRIMMING_HINT.fakeHint}`';
    expect(resolveDescription(raw, { fakeHint: 'Trim: fields ["a"].' })).toBe(
      'Fake summary.\n\nTrim: fields ["a"].'
    );
  });

  it('drops an unresolvable ${RESPONSE_TRIMMING_HINT.key} interpolation silently, like the bare form', () => {
    const raw = '`Fake summary. ${RESPONSE_TRIMMING_HINT.unknownHint} End.`';
    expect(resolveDescription(raw, {})).toBe('Fake summary.  End.');
  });
});

