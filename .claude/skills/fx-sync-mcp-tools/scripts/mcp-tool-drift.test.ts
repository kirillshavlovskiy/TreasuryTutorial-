describe('parseRegisteredModuleImports', () => {
  it('resolves only the imports actually referenced in the exported array', () => {
    const source = [
      "import * as fakeToolOne from '../tools/fake_domain/fake_tool_one';",
      "import * as fakeToolTwo from '../tools/fake_domain/fake_tool_two';",
      "import * as fakeToolDisabled from '../tools/fake_domain/fake_tool_disabled';",
      "",
      "export const registeredFinanceToolModules: ToolModule[] = [",
      "    fakeToolOne,",
      "    // fakeToolDisabled, // Disabled: mutation tools deferred for now",
      "    fakeToolTwo,",
      "] as unknown as ToolModule[];",
    ].join('\n');
    const { importedNames, importPathByName } = parseRegisteredModuleImports(source);
    expect([...importedNames].sort()).toEqual(['fakeToolOne', 'fakeToolTwo']);
    expect(importPathByName.get('fakeToolOne')).toBe('../tools/fake_domain/fake_tool_one');
    // Commented-out entries never reach the array body as a bare identifier line, so the
    // disabled tool is correctly excluded even though it is imported.
    expect(importedNames.has('fakeToolDisabled')).toBe(false);
  });

  it('returns empty sets when the array is absent', () => {
    const { importedNames, importPathByName } = parseRegisteredModuleImports('export const X = 1;');
    expect(importedNames.size).toBe(0);
    expect(importPathByName.size).toBe(0);
  });

  // registered_tools.ts is comment-dense (35+ `//` section headers in the real file). Found by
  // an independent Opus 5 review: a whole-line-only regex silently dropped any live entry that
  // didn't fit the exact shape "just a name, optionally followed by a comma, alone on its line" —
  // which would hide a genuinely new registration from drift detection rather than surface it.
  it('picks up a live entry that carries a trailing comment', () => {
    const source = [
      "import * as fakeToolOne from '../tools/fake_domain/fake_tool_one';",
      "",
      "export const registeredFinanceToolModules: ToolModule[] = [",
      "    fakeToolOne, // still live, kept for backwards compatibility",
      "] as unknown as ToolModule[];",
    ].join('\n');
    const { importedNames } = parseRegisteredModuleImports(source);
    expect([...importedNames]).toEqual(['fakeToolOne']);
  });

  it('picks up more than one entry written on the same line', () => {
    const source = [
      "import * as fakeToolOne from '../tools/fake_domain/fake_tool_one';",
      "import * as fakeToolTwo from '../tools/fake_domain/fake_tool_two';",
      "",
      "export const registeredFinanceToolModules: ToolModule[] = [",
      "    fakeToolOne, fakeToolTwo,",
      "] as unknown as ToolModule[];",
    ].join('\n');
    const { importedNames } = parseRegisteredModuleImports(source);
    expect([...importedNames].sort()).toEqual(['fakeToolOne', 'fakeToolTwo']);
  });

  it('does not pull a disabled name out of a comment trailing a real entry', () => {
    const source = [
      "import * as fakeToolOne from '../tools/fake_domain/fake_tool_one';",
      "import * as fakeToolDisabled from '../tools/fake_domain/fake_tool_disabled';",
      "",
      "export const registeredFinanceToolModules: ToolModule[] = [",
      "    fakeToolOne, // fakeToolDisabled would go here once re-enabled",
      "] as unknown as ToolModule[];",
    ].join('\n');
    const { importedNames } = parseRegisteredModuleImports(source);
    expect([...importedNames]).toEqual(['fakeToolOne']);
  });
});

describe('unescapeTableCell', () => {
  // sf_query_subsidiary_account_balance's real description contains `"trandate" | "posting_period"`
  // and `|x|<1e-9` — a literal pipe that the catalogue generator escapes as `\|` so the row
  // still parses as one markdown table cell. Reading it back without reversing that escape
  // reported this tool as changed on every single run, with zero actual drift.
  it('reverses the escaped-pipe markdown table cell convention', () => {
    expect(unescapeTableCell('balanceBasis ("trandate" \\| "posting_period")')).toBe(
      'balanceBasis ("trandate" | "posting_period")'
    );
  });

  it('leaves text with no escaped pipes unchanged', () => {
    expect(unescapeTableCell('Plain description, no pipes.')).toBe('Plain description, no pipes.');
  });
});

